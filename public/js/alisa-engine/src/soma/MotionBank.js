import * as THREE from 'three';

/**
 * ALISA Motion Bank
 * 
 * Extracts baked `THREE.AnimationClip` tracks from generic GLB files,
 * translates them using the SemanticBoneMap (Rosetta Stone), and
 * returns pure JSON-friendly data that can be re-applied to any
 * procedural skeleton sharing those semantic identifiers.
 */
export class MotionBank {

    /**
     * Extracts animations from a loaded GLTF scene.
     * @param {Object} gltf - The loaded GLTF object containing .animations
     * @param {Object} rosettaMap - The JSON dictionary (SemanticBoneMap)
     * @param {String} prefix - Prefix to identify these clips (e.g., 'fox')
     * @returns {Object} Extracted clips dictionary ready for Kinematic sampling
     */
    static extractFromGLTF(gltf, rosettaMap, prefix = 'bank') {
        const extractedClips = {};
        
        if (!gltf.animations || gltf.animations.length === 0) {
            console.warn(`[MotionBank] No animations found in GLTF for prefix ${prefix}`);
            return extractedClips;
        }

        gltf.animations.forEach(clip => {
            const clipDict = {};
            
            clip.tracks.forEach(track => {
                // Track names are typically "BoneName.position" or "BoneName.quaternion"
                const parts = track.name.split('.');
                const rawBoneName = parts[0];
                const property = parts[1]; // 'position', 'quaternion', 'scale'

                // Resolve Semantic Name via Rosetta Stone
                let semanticName = null;
                
                // 1. Direct match (e.g. "mixamorig:RightUpLeg")
                if (rosettaMap[rawBoneName]) {
                    semanticName = rosettaMap[rawBoneName];
                } else {
                    // 2. Substring match (e.g. sometimes GLTF parses colons out, or adds UUIDs)
                    for (const [key, value] of Object.entries(rosettaMap)) {
                        if (rawBoneName.includes(key) || rawBoneName.toLowerCase().includes(key.toLowerCase())) {
                            semanticName = value;
                            break;
                        }
                    }
                }

                // If this bone has no semantic mapping, we ignore its animation track
                // This ensures we only store data for bones ALISA cares about!
                if (!semanticName) return; 

                if (!clipDict[semanticName]) clipDict[semanticName] = {};
                
                clipDict[semanticName][property] = {
                    times: Array.from(track.times),
                    values: Array.from(track.values)
                };
            });

            // Store the clip
            const clipKey = `${prefix}:${clip.name.toLowerCase().replace(/\s+/g, '_')}`;
            extractedClips[clipKey] = {
                name: clip.name,
                duration: clip.duration,
                tracks: clipDict
            };
        });

        console.log(`[MotionBank] Extracted ${Object.keys(extractedClips).length} semantic clips under prefix '${prefix}'.`);
        return extractedClips;
    }

    /**
     * Interpolates the raw clip data and applies it to ALISA's live procedural bones.
     * @param {Object} clipData - The semantic clip dictionary (from extractFromGLTF)
     * @param {Number} t - The current clock time (in seconds)
     * @param {Array<THREE.Bone>} proceduralBones - The live array of semantic Bones generated by Geppetto
     */
    static sampleToBones(clipData, t, proceduralBones) {
        if (!clipData || !clipData.tracks) return;

        // Bucle ciclico: normalizamos el tiempo 't' a la duración del clip
        const loopT = t % clipData.duration;

        proceduralBones.forEach(bone => {
            // Buscamos el nombre del hueso usando una lógica de Semantic Rigging.
            // Para encontrar qué nodo es "L_Femur", podríamos necesitar que 'buildArchetypeSkeleton'
            // guarde el nombre semántico en bone.name o bone.userData.semanticName.
            // Puesto que Generamos esferas matemáticas, no todas tienen nombre todavía.
            // Por ahora, asumiremos que quien llame a sampleToBones ha asegurado que `bone.name` coincide.
            
            const semanticName = bone.name;
            if (!semanticName) return;

            const boneTracks = clipData.tracks[semanticName];
            if (!boneTracks) return;

            // Samplear Rotación (Quaternion)
            if (boneTracks.quaternion) {
                const times = boneTracks.quaternion.times;
                const values = boneTracks.quaternion.values; // flat array [x,y,z,w, x,y,z,w...]
                
                // Find interpolation bounds
                let i = 0;
                while (i < times.length - 1 && times[i + 1] <= loopT) {
                    i++;
                }

                if (i >= times.length - 1) {
                    // Reached end of clip
                    const lastIdx = times.length - 1;
                    bone.quaternion.set(
                        values[lastIdx * 4], values[lastIdx * 4 + 1], values[lastIdx * 4 + 2], values[lastIdx * 4 + 3]
                    ).normalize();
                } else {
                    // LERP entre i y i+1
                    const t0 = times[i];
                    const t1 = times[i+1];
                    const fraction = (loopT - t0) / (t1 - t0);

                    const q0 = new THREE.Quaternion(values[i*4], values[i*4+1], values[i*4+2], values[i*4+3]);
                    const q1 = new THREE.Quaternion(values[(i+1)*4], values[(i+1)*4+1], values[(i+1)*4+2], values[(i+1)*4+3]);
                    
                    bone.quaternion.slerpQuaternions(q0, q1, fraction).normalize();
                }
            }

            // Samplear Posición (Translate)
            if (boneTracks.position) {
                const times = boneTracks.position.times;
                const values = boneTracks.position.values; // flat array [x,y,z, x,y,z...]
                
                // Usually position tracks apply strongly to the ROOT bone (Pelvis/Spine).
                // Extracted GLB positions are in GLB local space, they might need scaling!
                // For now, we apply them directly.
                let i = 0;
                while (i < times.length - 1 && times[i + 1] <= loopT) i++;
                
                if (i >= times.length - 1) {
                    bone.position.set(values[i*3], values[i*3+1], values[i*3+2]);
                } else {
                    const t0 = times[i];
                    const t1 = times[i+1];
                    const fraction = (loopT - t0) / (t1 - t0);

                    const vx0 = values[i*3];     const vy0 = values[i*3+1];     const vz0 = values[i*3+2];
                    const vx1 = values[(i+1)*3]; const vy1 = values[(i+1)*3+1]; const vz1 = values[(i+1)*3+2];

                    bone.position.set(
                        vx0 + (vx1 - vx0) * fraction,
                        vy0 + (vy1 - vy0) * fraction,
                        vz0 + (vz1 - vz0) * fraction
                    );
                }
            }
        });
    }

}
