import * as THREE from 'three';

/**
 * Psyches.js - The Jungian Domain (El Alma / La Personalidad Base)
 * Maps mathematically to the v39_bestiario_enterprise_pneuma matrix.
 */

export const Psyches = {
    THE_ANIMA: 'anima',           // The Soul (Princess) - High curiosity, pure follow
    THE_HERALD: 'herald',         // The Messenger (Metatron) - Unstoppable forward momentum
    THE_SAGE: 'sage',             // The Sage (Solomon) - Static observation, analytical rotation
    THE_SENTINEL: 'sentinel',     // The Watchman (Kikiriki) - Perfect orbital distance, alert-trigger
    THE_SCIENTIST: 'scientist',   // Evaluator (Scully) - Maintains high ground, avoids direct contact
    THE_REBEL: 'rebel',           // Adversarial (Neo) - Unpredictable noise routing
    THE_SERVANT: 'servant',       // DevOps (WallE) - Sticks to allies to repair/follow
    THE_TRICKSTER: 'trickster',   // Shadow (Meowth/Ghost) - Tangential strafing, covers, backstabs
    NEUTRAL: 'neutral'
};

/**
 * Calculates the internal intentional vector bias before physical mechanics are applied.
 * @param {string} psyche The Jungian profile
 * @param {THREE.Vector3} currentPos Entity position
 * @param {THREE.Vector3} targetPos Stimulus position (if any)
 * @param {THREE.Vector3} baseIntent The default intent generated by the current state
 * @returns {THREE.Vector3} The modified intentional vector
 */
export function buildPsycheIntent(psyche, currentPos, targetPos, baseIntent) {
    if (!targetPos) return baseIntent;

    let modifiedIntent = baseIntent.clone();
    const dirToTarget = new THREE.Vector3().subVectors(targetPos, currentPos);
    dirToTarget.y = 0;
    const distToTarget = dirToTarget.length();
    
    if (distToTarget > 0) dirToTarget.normalize();

    switch(psyche) {
        case Psyches.THE_ANIMA:
            // Pure curiosity. Follows closely but stops right before collision.
            if (distToTarget > 2.0) modifiedIntent.copy(dirToTarget);
            else modifiedIntent.set(0,0,0);
            break;

        case Psyches.THE_SAGE:
            // Sages hold ground, only move if threat is extremely close (< 5)
            if (distToTarget > 5.0) {
                modifiedIntent.set(0,0,0); // Focus on target by rotation (engine handles it if vector isn't null, but here we null it to hold ground)
            } else {
                modifiedIntent.copy(dirToTarget).negate(); // Gracefully step back
            }
            break;
            
        case Psyches.THE_SENTINEL:
            // Sentinels orbit at a perfect medium distance (10) to keep watch
            if (distToTarget > 12) modifiedIntent.copy(dirToTarget);
            else if (distToTarget < 8) modifiedIntent.copy(dirToTarget).negate();
            else modifiedIntent.set(-dirToTarget.z, 0, dirToTarget.x); // Orbital tangent
            break;

        case Psyches.THE_TRICKSTER:
            // Combines forward movement with erratic strafing to stay off-center
            const strafe = new THREE.Vector3(-dirToTarget.z, 0, dirToTarget.x);
            modifiedIntent.lerp(strafe, 0.7).normalize();
            break;
            
        case Psyches.THE_REBEL:
            // True adversarial noise (Perlin-like simple replacement)
            const timePhase = Date.now() * 0.005;
            modifiedIntent.x += Math.sin(timePhase * 1.3) * 2;
            modifiedIntent.z += Math.cos(timePhase * 0.8) * 2;
            modifiedIntent.normalize();
            break;
            
        case Psyches.THE_HERALD:
            // Direct relentless approach, zero lateral movement.
            // Ignored physics resistance will be handled in Conductas
            modifiedIntent.copy(dirToTarget);
            break;

        case Psyches.THE_SCIENTIST:
            // Retreats to highest topological point available and stops.
            // (Abstracted here as moving away but at a much slower, calculated angular pace)
            if (distToTarget < 20.0) {
                modifiedIntent.copy(dirToTarget).negate().add(new THREE.Vector3(0.2, 0, 0.2)).normalize();
            } else {
                modifiedIntent.set(0,0,0);
            }
            break;

        case Psyches.THE_SERVANT:
            // Intended to follow SIBLINGS, but if target is stimulus, orbits closely
            if (distToTarget > 4.0) modifiedIntent.copy(dirToTarget);
            else modifiedIntent.set(-dirToTarget.z, 0, dirToTarget.x).multiplyScalar(0.5); // Tight slow orbit
            break;
    }

    return modifiedIntent;
}
